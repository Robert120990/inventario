import { formatDate } from './formatUtils.js';

/**
 * Formats a Date object as YYYY-MM-DD in local calendar time.
 * @param {Date} d
 * @returns {string}
 */
export const toLocalDateStr = (d = new Date()) => {
  if (!(d instanceof Date) || Number.isNaN(d.getTime())) return '';
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
};

/**
 * Safely normalizes any calendar date representation ('YYYY-MM-DD', ISO date string, or Date)
 * to a clean 'YYYY-MM-DD' string without UTC timezone shifts.
 * @param {string|Date|null|undefined} val
 * @returns {string}
 */
export const normalizeDateOnly = (val) => {
  if (!val) return '';
  if (val instanceof Date) {
    return toLocalDateStr(val);
  }
  const str = String(val).trim();
  const match = str.match(/^(\d{4}-\d{2}-\d{2})/);
  if (match) return match[1];
  const parsed = new Date(str);
  if (!Number.isNaN(parsed.getTime())) {
    return toLocalDateStr(parsed);
  }
  return '';
};

/**
 * Adds (or subtracts) calendar days from a 'YYYY-MM-DD' string using local noon (12:00:00)
 * so Daylight Saving Time and UTC conversions never shift the day.
 * @param {string} dateStr
 * @param {number} daysToAdd
 * @returns {string}
 */
export const addDaysToDateStr = (dateStr, daysToAdd = 1) => {
  const clean = normalizeDateOnly(dateStr);
  if (!clean) return '';
  const [y, m, d] = clean.split('-').map(Number);
  if (!y || !m || !d) return '';
  const dt = new Date(y, m - 1, d + Number(daysToAdd || 0), 12, 0, 0);
  return toLocalDateStr(dt);
};

/**
 * Builds an inclusive list of 'YYYY-MM-DD' calendar dates from startDate to endDate.
 * @param {string} startDate
 * @param {string} endDate
 * @returns {string[]}
 */
export const buildInclusiveDateRange = (startDate, endDate) => {
  const startStr = normalizeDateOnly(startDate);
  const endStr = normalizeDateOnly(endDate);
  if (!startStr || !endStr || startStr > endStr) return [];
  const dates = [];
  let curr = startStr;
  let safety = 0;
  while (curr && curr <= endStr && safety < 3700) {
    dates.push(curr);
    curr = addDaysToDateStr(curr, 1);
    safety++;
  }
  return dates;
};

/**
 * Resolves the authoritative period (startDate, endDate, title) of a frozen daily cut.
 * If the cut contains daily table rows (congeladosData / preparadosData) with valid 'fecha'
 * entries, ensures startDate and endDate always match the actual frozen daily series so
 * stale or accidentally overwritten header dates cannot misrepresent the cut.
 * @param {object} cut
 * @returns {{ startDate: string, endDate: string, title: string }}
 */
export const resolveCutPeriod = (cut) => {
  if (!cut) return { startDate: '', endDate: '', title: '' };

  const rawStart = normalizeDateOnly(cut.startDate);
  const rawEnd = normalizeDateOnly(cut.endDate);

  let cong = [];
  let prep = [];
  if (Array.isArray(cut.congeladosData)) {
    cong = cut.congeladosData;
  } else if (typeof cut.congeladosData === 'string' && cut.congeladosData.trim()) {
    try { cong = JSON.parse(cut.congeladosData); } catch { cong = []; }
  }
  if (Array.isArray(cut.preparadosData)) {
    prep = cut.preparadosData;
  } else if (typeof cut.preparadosData === 'string' && cut.preparadosData.trim()) {
    try { prep = JSON.parse(cut.preparadosData); } catch { prep = []; }
  }

  const rowDates = [];
  for (const r of cong) {
    const d = normalizeDateOnly(r?.fecha);
    if (d) rowDates.push(d);
  }
  for (const r of prep) {
    const d = normalizeDateOnly(r?.fecha);
    if (d) rowDates.push(d);
  }
  rowDates.sort();

  const hasRowDates = !cut.isSummaryOnly && rowDates.length > 0;
  const effectiveStart = hasRowDates ? rowDates[0] : rawStart;
  const effectiveEnd = hasRowDates ? rowDates[rowDates.length - 1] : rawEnd;

  const rawTitle = String(cut.title || '').trim();
  const isAutoGeneratedTitle = /^Corte\s+\d{2}\/\d{2}\/\d{4}\s+al\s+\d{2}\/\d{2}\/\d{4}$/i.test(rawTitle)
    || /^Corte\s+\d{4}-\d{2}-\d{2}\s+al\s+\d{4}-\d{2}-\d{2}$/i.test(rawTitle);

  let effectiveTitle = rawTitle;
  if (!effectiveTitle || isAutoGeneratedTitle) {
    if (effectiveStart && effectiveEnd) {
      effectiveTitle = `Corte ${formatDate(effectiveStart)} al ${formatDate(effectiveEnd)}`;
    }
  }

  return {
    startDate: effectiveStart,
    endDate: effectiveEnd,
    title: effectiveTitle
  };
};

/**
 * Computes the default live period (startDate .. endDate) for Resumen Diario based on
 * registered daily cuts:
 * - Finds the latest cut's endDate (e.g. day 28 -> '2026-10-28').
 * - Sets startDate to the immediate next calendar day (day 29 -> '2026-10-29').
 * - Sets endDate to todayStr (or startDate if startDate > todayStr).
 * - If no cuts exist yet, defaults to the 1st of the current month through todayStr.
 * @param {Array} cuts
 * @param {string} [todayStr]
 * @returns {{ startDate: string, endDate: string, lastCutEndDate: string|null }}
 */
export const computeNextLiveCutRange = (cuts = [], todayStr = toLocalDateStr(new Date())) => {
  const cleanToday = normalizeDateOnly(todayStr) || toLocalDateStr(new Date());
  const defaultMonthStart = `${cleanToday.slice(0, 8)}01`;

  if (!Array.isArray(cuts) || cuts.length === 0) {
    return {
      startDate: defaultMonthStart,
      endDate: cleanToday,
      lastCutEndDate: null
    };
  }

  const endDates = cuts
    .map(c => resolveCutPeriod(c).endDate)
    .filter(Boolean)
    .sort((a, b) => b.localeCompare(a));

  if (endDates.length === 0) {
    return {
      startDate: defaultMonthStart,
      endDate: cleanToday,
      lastCutEndDate: null
    };
  }

  const lastCutEndDate = endDates[0];
  const nextStart = addDaysToDateStr(lastCutEndDate, 1);
  const nextEnd = nextStart > cleanToday ? nextStart : cleanToday;

  return {
    startDate: nextStart,
    endDate: nextEnd,
    lastCutEndDate
  };
};
